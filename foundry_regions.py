PARENTHETICAL_NOTE_RE = re.compile(r"\s*[（(][^（）()]*[）)]\s*")


def normalize_region_key(region_name: str) -> str:
    """把用户输入变成便于查表的 key，忽略空格、横线、下划线和括号备注。"""
    region_without_notes = PARENTHETICAL_NOTE_RE.sub("", region_name).strip()
    return re.sub(r"[\s_-]+", "", region_without_notes).lower()


REGION_LOOKUP = {
    normalize_region_key(region_name): location
    for region_name, location in REGION_NAME_MAP.items()
}


def normalize_location(region_name: str) -> str:
    """把 CSV 里的 Region 转成 Azure CLI 接受的 location code。"""
    normalized_region = normalize_region_key(region_name.strip())
    return REGION_LOOKUP.get(normalized_region, normalized_region)
